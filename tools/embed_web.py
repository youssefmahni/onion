#!/usr/bin/env python3
"""Generate the embedded web-assets source for the dashboard (plan §3.1).

Scans <web_dir> (excluding the legacy dashboard.html, which stays disk-loaded)
and writes a C++ file exposing `onion::cli::web_assets()`: a static map of
asset name -> {bytes, mime, sha256}. Each file is embedded as a raw string
literal with a delimiter chosen to not occur in the content.

Usage: embed_web.py <web_dir> <output.cpp>
"""

import hashlib
import sys
from pathlib import Path

MIME = {
    ".html": "text/html",
    ".js": "text/javascript",
    ".css": "text/css",
    ".json": "application/json",
    ".svg": "image/svg+xml",
    ".png": "image/png",
    ".woff2": "font/woff2",
}

SKIP = set()  # D6: the legacy disk-loaded page is gone


def raw_string(data: bytes) -> str:
    text = data.decode("utf-8")
    delimiter = "R"
    while (")\"" + delimiter + "\"") in text:
        delimiter += "R"
    return f'R"onion{delimiter}({text})onion{delimiter}"'


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__)
        return 2
    web_dir = Path(sys.argv[1])
    output = Path(sys.argv[2])

    files = sorted(
        path
        for path in web_dir.rglob("*")
        if path.is_file()
        and path.name not in SKIP
        and not any(part.startswith(".") for part in path.relative_to(web_dir).parts)
    )
    entries = []
    for path in files:
        data = path.read_bytes()
        name = path.relative_to(web_dir).as_posix()
        mime = MIME.get(path.suffix, "application/octet-stream")
        digest = hashlib.sha256(data).hexdigest()
        entries.append(
            f'    {{"{name}", {{std::string({raw_string(data)}), '
            f'"{mime}", "{digest}"}}}},'
        )

    output.write_text(
        "// Generated by tools/embed_web.py — do not edit.\n"
        "#include <map>\n"
        "#include <string>\n"
        '#include "api/api.hpp"\n'
        "\n"
        "namespace onion::cli {\n"
        "\n"
        "const std::map<std::string, onion::api::StaticFile>& web_assets() {\n"
        "  static const std::map<std::string, onion::api::StaticFile> assets = {\n"
        + "\n".join(entries)
        + "\n  };\n"
        "  return assets;\n"
        "}\n"
        "\n"
        "}  // namespace onion::cli\n",
        encoding="utf-8",  # the shell contains non-ASCII (arrows etc.)
    )
    return 0


if __name__ == "__main__":
    sys.exit(main())
